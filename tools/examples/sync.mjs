// Copies the README of each project in BitMagic.Examples into the website, so
// the examples are documented in one place: the README is the source, and the
// page under Examples/ is generated from it.
//
// Run from a full superproject checkout (BitMagic.Examples and BitMagic.VSC
// must be siblings of BitMagic.Documentation), after `npm install` in
// tools/highlight: `node tools/examples/sync.mjs`.
//
// For every entry in `examples` below this writes:
//   - Examples/<Page>.md, the page itself (don't edit it, edit the README)
//   - Images/examples/<slug>/*, any images the README links to
//   - _data/examples.yml, which drives the Examples index page and the nav
// Re-run after changing a README, and commit the output.

